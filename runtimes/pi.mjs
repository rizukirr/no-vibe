// runtimes/pi.mjs
export const id = 'pi'

import { json, markdownCommand } from '../lib/emit.mjs'

// The guard and status logic live in hooks/*.sh. The extension maps Pi's
// tool payload to the Claude hook JSON and runs the same scripts.
const EXTENSION = `// Generated by no-vibe. Do not edit.
import { existsSync, realpathSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// Resolve symlinks first: a symlinked install loads this file from outside the package.
const HOOKS = path.resolve(path.dirname(realpathSync(fileURLToPath(import.meta.url))), '../../../hooks')

function runHook(script: string, payload: object) {
  return spawnSync('bash', [path.join(HOOKS, script)], { input: JSON.stringify(payload), encoding: 'utf8' })
}

function toClaude(event: any, cwd: string): [string, object] | null {
  const input = event.input ?? {}
  switch (event.toolName) {
    case 'write': return ['block-writes.sh', { tool_name: 'Write', tool_input: { file_path: input.path }, cwd }]
    case 'edit': return ['block-writes.sh', { tool_name: 'Edit', tool_input: { file_path: input.path }, cwd }]
    case 'bash': return ['block-bash-writes.sh', { tool_name: 'Bash', tool_input: { command: input.command }, cwd }]
    default: return null
  }
}

export default function (pi: any) {
  pi.on('before_agent_start', async (event: any, ctx: any) => {
    const result = runHook('status.sh', { cwd: ctx?.cwd ?? process.cwd() })
    const text = result.status === 0 ? result.stdout.trim() : ''
    if (text) return { systemPrompt: \`\${event.systemPrompt}\\n\\n\${text}\` }
  })

  // A guard that cannot run refuses while no-vibe is active: an unenforced
  // guard is worse than a blocked write.
  pi.on('tool_call', async (event: any, ctx: any) => {
    const cwd = ctx?.cwd ?? process.cwd()
    if (!existsSync(path.join(cwd, '.no-vibe', 'active'))) return
    if (event.toolName === 'powershell') {
      return { block: true, reason: 'no-vibe mode is active. PowerShell is refused while learning. Show the code in chat and let the user type it.' }
    }
    const call = toClaude(event, cwd)
    if (!call) return
    const result = runHook(call[0], call[1])
    if (result.error || result.status !== 0) {
      return { block: true, reason: result.stderr?.trim() || 'no-vibe: the write guard could not run' }
    }
  })
}
`

export function emit(model) {
  const { config, skills } = model
  const files = {
    '.pi-plugin/extensions/no-vibe/index.ts': EXTENSION,
    '.pi-plugin/plugin.json': json({ name: config.name, description: config.description, version: config.version }),
  }
  for (const skill of skills.filter(s => s.command)) {
    files[`.pi-plugin/prompts/${skill.name}.md`] = markdownCommand(skill)
  }
  return files
}

export function pkg() {
  return {
    pi: {
      skills: ['./skills'],
      prompts: ['./.pi-plugin/prompts'],
      extensions: ['./.pi-plugin/extensions'],
    },
  }
}

export function ships() {
  return ['.pi-plugin/']
}
