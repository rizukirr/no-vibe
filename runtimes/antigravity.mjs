// runtimes/antigravity.mjs
export const id = 'antigravity'

import { json } from '../lib/emit.mjs'

// Antigravity has no session-start event. rules/ is the only always-on
// channel, so it carries the instruction to check for the marker.
const RULES = `<!-- Generated by no-vibe. Do not edit. -->

# no-vibe

If \`.no-vibe/active\` exists at the workspace root, no-vibe learning mode is ON. Load the \`no-vibe\` skill before replying and follow it. If \`.no-vibe/syllabus.md\` has \`status: approved\`, resume it as the skill describes.

While no-vibe is ON, never write to the user's project files by any tool. Writes are allowed only under \`.no-vibe/\`, \`~/.no-vibe/\`, \`/tmp/\` and \`/var/tmp/\`.
`

export function emit(model) {
  const { config } = model
  return {
    'plugin.json': json({ name: config.name, description: config.description }),
    'hooks.json': json({
      'no-vibe-guard': {
        PreToolUse: [{
          matcher: 'write_to_file|replace_file_content|multi_replace_file_content|run_command',
          hooks: [{ type: 'command', command: './hooks/run-hook.cmd agy-guard.sh', timeout: 10 }],
        }],
      },
    }),
    'rules/AGENTS.md': RULES,
  }
}

export function ships() {
  return ['plugin.json', 'hooks.json', 'rules/']
}
