// runtimes/opencode.mjs
export const id = 'opencode'

// The guard and status logic live in hooks/*.sh. The plugin maps opencode's
// tool payload to the Claude hook JSON and runs the same scripts.
function plugin(model) {
  const list = model.skills
    .map(skill => `  ${JSON.stringify({ name: skill.name, description: skill.description })},`)
    .join('\n')
  return `// Generated by no-vibe. Do not edit.
import { existsSync, readFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const SKILLS = path.join(ROOT, 'skills')
const HOOKS = path.join(ROOT, 'hooks')
const LIST = [
${list}
]

function runHook(script, payload) {
  return spawnSync('bash', [path.join(HOOKS, script)], { input: JSON.stringify(payload), encoding: 'utf8' })
}

function toClaude(ev, cwd) {
  const input = ev.input ?? {}
  switch (ev.tool) {
    case 'write': return ['block-writes.sh', { tool_name: 'Write', tool_input: { file_path: input.path }, cwd }]
    case 'edit': return ['block-writes.sh', { tool_name: 'Edit', tool_input: { file_path: input.path }, cwd }]
    case 'patch': return ['block-writes.sh', { tool_name: 'apply_patch', tool_input: { command: input.patchText }, cwd }]
    case 'shell': return ['block-bash-writes.sh', { tool_name: 'Bash', tool_input: { command: input.command }, cwd }]
    default: return null
  }
}

// A guard that cannot run refuses while no-vibe is active: an unenforced
// guard is worse than a blocked write.
function guard(ev, cwd = process.cwd()) {
  if (!existsSync(path.join(cwd, '.no-vibe', 'active'))) return
  const call = toClaude(ev, cwd)
  if (!call) return
  const result = runHook(...call)
  if (result.error || result.status !== 0) {
    throw new Error(result.stderr?.trim() || \`no-vibe: the write guard could not run (\${result.error?.message ?? \`exit \${result.status}\`})\`)
  }
}

function status(cwd = process.cwd()) {
  const result = runHook('status.sh', { cwd })
  return result.status === 0 ? result.stdout.trim() : ''
}

export default {
  id: ${JSON.stringify(model.config.name)},
  setup: async ctx => {
    // The background service runs from its own cwd, not the project's.
    const dir = ctx.location?.directory
    await ctx.skill.transform(draft => {
      for (const { name, description } of LIST) {
        const file = path.join(SKILLS, name, 'SKILL.md')
        const content = readFileSync(file, 'utf8').replace(/^---\\r?\\n[\\s\\S]*?\\r?\\n---(?:\\r?\\n)?/, '')
        draft.add({ id: name, name, description, path: file, content })
      }
    })
    await ctx.tool.hook('execute.before', ev => guard(ev, dir))
    // The context hook fires before every model request, so the status line
    // is computed once per session.
    const seen = new Map()
    await ctx.session.hook('context', ev => {
      if (!seen.has(ev.sessionID)) seen.set(ev.sessionID, status(dir))
      const text = seen.get(ev.sessionID)
      if (text) ev.system.push({ type: 'text', text })
    })
  },
}
`
}

function commandFile(skill) {
  return [
    '---',
    `description: ${JSON.stringify(skill.description)}`,
    '---',
    '',
    '<!-- Generated by no-vibe. Do not edit. -->',
    '',
    `Invoke the \`${skill.name}\` skill and follow it exactly.`,
    '',
    '**User intent:** $ARGUMENTS',
    '',
  ].join('\n')
}

function installDoc(config) {
  return [
    `# Installing ${config.name} for opencode`,
    '',
    '<!-- Generated by no-vibe. Do not edit. -->',
    '',
    'Requires opencode v2 and `bash` and `jq` on PATH. Without bash, every tool call that writes is refused while no-vibe is on.',
    '',
    'Add the package to the `plugin` array in `opencode.json`:',
    '',
    '```json',
    '{',
    `  "plugin": ["${config.name}@git+${config.repository}.git"]`,
    '}',
    '```',
    '',
    'Run `opencode reload`, then check the skills registered. From your project directory:',
    '',
    '```',
    `opencode api skill.list -H "x-opencode-directory:$PWD" | grep -c '"id":"${config.name}"'`,
    '```',
    '',
    'It prints `1` when the skills are registered.',
    '',
  ].join('\n')
}

export function emit(model) {
  const files = {
    '.opencode/plugins/no-vibe.js': plugin(model),
    '.opencode/INSTALL.md': installDoc(model.config),
  }
  for (const skill of model.skills.filter(s => s.command)) {
    files[`.opencode/commands/${skill.name}.md`] = commandFile(skill)
  }
  return files
}

export function pkg() {
  return { main: './.opencode/plugins/no-vibe.js' }
}

export function ships() {
  return ['.opencode/']
}
