import assert from 'node:assert/strict'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build, fsReader } from '../lib/build.mjs'
import { parseFrontmatter } from '../lib/frontmatter.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

// A freshly generated tree has nothing to write or remove.
const clean = await build(root)
assert.deepEqual(clean.write, [], `stale generated files: ${clean.write.join(', ')}`)
assert.deepEqual(clean.remove, [], `orphan generated files: ${clean.remove.join(', ')}`)

// A hand edit to a generated file is reported as stale.
const disk = fsReader(root)
const edited = { read: file => (file === 'package.json' ? `${disk.read(file)} ` : disk.read(file)) }
const tampered = await build(root, edited)
assert.ok(tampered.write.includes('package.json'), 'a hand-edited package.json must be reported stale')

// Whole generated files carry the do-not-edit marker. JSON cannot hold a
// comment, and region-owned files are hand-written outside their regions.
for (const [file, text] of Object.entries(clean.files)) {
  if (file.endsWith('.json') || file === '.no-vibe-manifest') continue
  if (text.includes('<!-- no-vibe:generated:')) continue
  assert.ok(text.includes('Generated by no-vibe. Do not edit.'), `${file} lacks the generated marker`)
}

// The version is stated once, in the config.
const config = JSON.parse(disk.read('no-vibe.config.json'))
for (const [file, text] of Object.entries(clean.files)) {
  if (!file.endsWith('.json')) continue
  const json = JSON.parse(text)
  const versions = [json.version, ...(json.plugins ?? []).map(p => p.version)].filter(Boolean)
  for (const v of versions) assert.equal(v, config.version, `${file} version`)
}

// Frontmatter written on Windows or with YAML quote escapes.
const crlf = parseFrontmatter('---\r\nname: x\r\ndescription: y\r\n---\r\nbody\r\n')
assert.deepEqual(crlf.data, { name: 'x', description: 'y' })
assert.equal(crlf.body, 'body\r\n')
assert.equal(parseFrontmatter("---\nd: 'it''s x: y'\n---\n").data.d, "it's x: y")
assert.equal(parseFrontmatter('---\nd: "a \\"b\\": c"\n---\n').data.d, 'a "b": c')

// Quoting the restricted subset does not support is an error, not a misparse.
assert.throws(() => parseFrontmatter('---\nd: "x" and "y"\n---\n'), /unsupported escape or an unescaped quote/)
assert.throws(() => parseFrontmatter('---\nd: "x\\ny"\n---\n'), /unsupported escape or an unescaped quote/)
assert.throws(() => parseFrontmatter("---\nd: 'it's'\n---\n"), /unsupported escape or an unescaped quote/)

console.log('test_generate: ok')
